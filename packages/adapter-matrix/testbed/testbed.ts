      name: 'Dither Testbed',
      topic: 'Local Matrix testbed for the dither-chat adapter',
      preset: 'public_chat',
      room_alias_name: 'testbed',
      creation_content: { type: 'm.space' },
      power_level_content_override: { events_default: 100 },
