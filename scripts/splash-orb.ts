// Writes apps/android/.../drawable/splash_orb.xml from ui/Loader.tsx: its first frame, cells grouped by Bayer level and faded in in that order. Run from the repo root: bun scripts/splash-orb.ts
const src = await Bun.file('packages/web/src/ui/Loader.tsx').text();
const BAYER = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5];
const N = 16;
const body = src.slice(src.indexOf('function frame'), src.indexOf('let frames')).replace('(angle: number, reveal = 16): string', '(angle, reveal = 16)');
const frame = new Function('BAYER', 'N', body + '; return frame;')(BAYER, N);
const d: string = frame(-Math.PI * 0.75);
// 88dp on screen: the splash draws a 108-unit viewport at 288dp, so a cell is 5.5dp = 2.0625 units.
const cell = 2.0625, off = (108 - N * cell) / 2;
const levels: string[][] = Array.from({ length: 16 }, () => []);
for (const m of d.matchAll(/M(\d+) (\d+)/g)) {
  const x = +m[1], y = +m[2];
  const X = (off + x * cell).toFixed(4).replace(/\.?0+$/, ''), Y = (off + y * cell).toFixed(4).replace(/\.?0+$/, '');
  levels[BAYER[(y % 4) * 4 + (x % 4)]].push(`M${X},${Y}h${cell}v${cell}h-${cell}z`);
}
let paths = '', anims = '';
levels.forEach((ps, k) => {
  if (!ps.length) return;
  paths += `            <path android:name="b${k}" android:fillColor="@color/accent" android:fillAlpha="0" android:pathData="${ps.join('')}"/>\n`;
  anims += `    <target android:name="b${k}">
        <aapt:attr name="android:animation">
            <objectAnimator android:propertyName="fillAlpha" android:valueFrom="0" android:valueTo="1" android:startOffset="${k * 34}" android:duration="40"/>
        </aapt:attr>
    </target>
`;
});
const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- The launch splash: the web loader's sphere (packages/web/src/ui/Loader.tsx), dithering in cell by cell in Bayer
     order, at the size and place the page then draws it (88dp, centred). Generated by scripts/splash-orb.ts. -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt">
    <aapt:attr name="android:drawable">
        <vector android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
${paths}        </vector>
    </aapt:attr>
${anims}</animated-vector>
`;
await Bun.write('apps/android/app/src/main/res/drawable/splash_orb.xml', xml);
console.log(levels.map((l) => l.length).join(' '));

export {};
